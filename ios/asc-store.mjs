#!/usr/bin/env node
// Fills in the App Store listing for Red Wedge Timer and submits it.
//
//   node asc-store.mjs status          # version, localisations, what is missing
//   node asc-store.mjs metadata        # description, keywords, URLs, what's new
//   node asc-store.mjs screenshots     # upload ios/store/screenshots/*.png
//   node asc-store.mjs age-rating      # the questionnaire, all "none"
//   node asc-store.mjs build           # attach the processed build to the version
//   node asc-store.mjs submit          # send it to review
//
// Credentials from the environment, as with asc-provision.mjs.

import { createSign, createPrivateKey, createHash } from 'node:crypto';
import { readFile, readdir } from 'node:fs/promises';

