function env(name) {
	const value = process.env[name];
	if (!value) throw new Error(`missing ${name}`);
	return value;
}

async function token() {
	const p8 = await readFile(env('APPSTORECONNECT_P8'), 'utf8');
	const now = Math.floor(Date.now() / 1000);
	const encode = (o) => Buffer.from(JSON.stringify(o)).toString('base64url');
	const head = encode({ alg: 'ES256', kid: env('APPSTORECONNECT_KEY_ID'), typ: 'JWT' });
	const body = encode({
		iss: env('APPSTORECONNECT_ISSUER_ID'),
		iat: now, exp: now + 900, aud: 'appstoreconnect-v1',
	});
	const signer = createSign('SHA256');
	signer.update(`${head}.${body}`);
	const sig = signer.sign({ key: createPrivateKey(p8), dsaEncoding: 'ieee-p1363' });
	return `${head}.${body}.${sig.toString('base64url')}`;
}

async function call(method, path, body) {
	const res = await fetch(path.startsWith('http') ? path : `${API}${path}`, {
		method,
		headers: {
			Authorization: `Bearer ${await token()}`,
			'Content-Type': 'application/json',
		},
		body: body ? JSON.stringify(body) : undefined,
	});
	const text = await res.text();
	const json = text ? JSON.parse(text) : {};
	if (!res.ok) {
		const detail = (json.errors ?? []).map((e) => `${e.title}: ${e.detail}`).join('\n  ');
		throw new Error(`${method} ${path} -> ${res.status}\n  ${detail || text}`);
	}
	return json;
}

async function version() {
	const found = await call('GET', `/apps/${APP_ID}/appStoreVersions?limit=5`);
	// the app record carries a macOS version record too; we want the iOS one
	const match = found.data.find(
		(v) => v.attributes.versionString === VERSION && v.attributes.platform === 'IOS'
	);
	if (match) return match;
	const made = await call('POST', '/appStoreVersions', {
		data: {
			type: 'appStoreVersions',
			attributes: { platform: 'IOS', versionString: VERSION },
			relationships: { app: { data: { type: 'apps', id: APP_ID } } },
		},
	});
	console.log('created version', VERSION);
	return made.data;
}

async function localisation(versionId) {
	const list = await call('GET', `/appStoreVersions/${versionId}/appStoreVersionLocalizations?limit=20`);
	const match = list.data.find((l) => l.attributes.locale === LOCALE);
	if (match) return match;
	const made = await call('POST', '/appStoreVersionLocalizations', {
		data: {
			type: 'appStoreVersionLocalizations',
			attributes: { locale: LOCALE },
			relationships: { appStoreVersion: { data: { type: 'appStoreVersions', id: versionId } } },
		},
	});
	return made.data;
}

async function status() {
	const app = await call('GET', `/apps/${APP_ID}`);
	console.log('app       :', app.data.attributes.name, '|', app.data.attributes.bundleId);

	const versions = await call('GET', `/apps/${APP_ID}/appStoreVersions?limit=5`);
	for (const v of versions.data) {
		console.log('version   :', v.attributes.versionString, '|', v.attributes.appStoreState, '| id', v.id);
	}

	const builds = await call('GET', `/builds?filter[app]=${APP_ID}&limit=5`);
	for (const b of builds.data) {
		console.log('build     :', b.attributes.version, '|', b.attributes.processingState, '| id', b.id);
	}
	if (builds.data.length === 0) console.log('build     : none listed yet (still processing)');

	const infos = await call('GET', `/apps/${APP_ID}/appInfos?limit=5`);
	for (const i of infos.data) {
		console.log('appInfo   :', i.id, '| state', i.attributes.appStoreState);
	}
}

async function metadata() {
	const v = await version();
	const l = await localisation(v.id);
	await call('PATCH', `/appStoreVersionLocalizations/${l.id}`, {
		data: {
			type: 'appStoreVersionLocalizations',
			id: l.id,
			attributes: {
				description: LISTING.description,
				keywords: LISTING.keywords,
				promotionalText: LISTING.promotionalText,
				supportUrl: LISTING.supportUrl,
				...(LISTING.marketingUrl ? { marketingUrl: LISTING.marketingUrl } : {}),
			},
		},
	});
	console.log('wrote description, keywords, promo text, support URL and release notes');
}

async function screenshots() {
	const v = await version();
	const l = await localisation(v.id);
	const sets = await call('GET', `/appStoreVersionLocalizations/${l.id}/appScreenshotSets?limit=10`);
	let set = sets.data.find((s) => s.attributes.screenshotDisplayType === 'APP_IPHONE_67');
	if (!set) {
		const made = await call('POST', '/appScreenshotSets', {
			data: {
				type: 'appScreenshotSets',
				attributes: { screenshotDisplayType: 'APP_IPHONE_67' },
				relationships: {
					appStoreVersionLocalization: {
						data: { type: 'appStoreVersionLocalizations', id: l.id },
					},
				},
			},
		});
		set = made.data;
	}

	const existing = await call('GET', `/appScreenshotSets/${set.id}/appScreenshots?limit=10`);
	if (existing.data.length > 0) {
		console.log(`${existing.data.length} screenshot(s) already uploaded; nothing to do`);
		return;
	}

	const dir = 'store/screenshots';
	for (const name of (await readdir(dir)).filter((f) => f.endsWith('.png')).sort()) {
		const bytes = await readFile(`${dir}/${name}`);
		const reserved = await call('POST', '/appScreenshots', {
			data: {
				type: 'appScreenshots',
				attributes: { fileName: name, fileSize: bytes.length },
				relationships: {
					appScreenshotSet: { data: { type: 'appScreenshotSets', id: set.id } },
				},
			},
		});
		for (const op of reserved.data.attributes.uploadOperations) {
			const headers = Object.fromEntries(op.requestHeaders.map((h) => [h.name, h.value]));
			const slice = bytes.subarray(op.offset, op.offset + op.length);
			const put = await fetch(op.url, { method: op.method, headers, body: slice });
			if (!put.ok) throw new Error(`upload of ${name} failed: ${put.status}`);
		}
		await call('PATCH', `/appScreenshots/${reserved.data.id}`, {
			data: {
				type: 'appScreenshots',
				id: reserved.data.id,
				attributes: {
					uploaded: true,
					sourceFileChecksum: createHash('md5').update(bytes).digest('hex'),
				},
			},
		});
		console.log('uploaded', name);
	}
}

async function appInfo() {
	const infos = await call('GET', `/apps/${APP_ID}/appInfos?limit=5`);
	const editable = infos.data.find((i) => i.attributes.appStoreState === 'PREPARE_FOR_SUBMISSION');
	return editable ?? infos.data[0];
}

