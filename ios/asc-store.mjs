async function reviewDetail() {
	const v = await version();
	const existing = await call('GET', `/appStoreVersions/${v.id}/appStoreReviewDetail`).catch(() => null);
	if (existing?.data?.id) {
		await call('PATCH', `/appStoreReviewDetails/${existing.data.id}`, {
			data: { type: 'appStoreReviewDetails', id: existing.data.id, attributes: REVIEW_CONTACT },
		});
		console.log('updated the App Review contact details');
		return;
	}
	await call('POST', '/appStoreReviewDetails', {
		data: {
			type: 'appStoreReviewDetails',
			attributes: REVIEW_CONTACT,
			relationships: { appStoreVersion: { data: { type: 'appStoreVersions', id: v.id } } },
		},
	});
	console.log('wrote the App Review contact details');
}

async function attachBuild() {
	const v = await version();
	const builds = await call('GET', `/builds?filter[app]=${APP_ID}&limit=10`);
	const ready = builds.data.find((b) => b.attributes.processingState === 'VALID');
	if (!ready) {
		console.log('no processed build yet; wait and try again');
		return;
	}
	await call('PATCH', `/appStoreVersions/${v.id}/relationships/build`, {
		data: { type: 'builds', id: ready.id },
	});
	console.log('attached build', ready.attributes.version, `(${ready.id})`);
}

async function submit() {
	const v = await version();
	const made = await call('POST', '/reviewSubmissions', {
		data: {
			type: 'reviewSubmissions',
			attributes: { platform: 'IOS' },
			relationships: { app: { data: { type: 'apps', id: APP_ID } } },
		},
	}).catch(async (error) => {
		// one open submission at a time; reuse it
		const open = await call('GET', `/apps/${APP_ID}/reviewSubmissions?filter[state]=READY_FOR_REVIEW,WAITING_FOR_REVIEW,UNRESOLVED_ISSUES&limit=1`);
		if (open.data?.[0]) return { data: open.data[0] };
		throw error;
	});

	await call('POST', '/reviewSubmissionItems', {
		data: {
			type: 'reviewSubmissionItems',
			relationships: {
				reviewSubmission: { data: { type: 'reviewSubmissions', id: made.data.id } },
				appStoreVersion: { data: { type: 'appStoreVersions', id: v.id } },
			},
		},
	});

	await call('PATCH', `/reviewSubmissions/${made.data.id}`, {
		data: { type: 'reviewSubmissions', id: made.data.id, attributes: { submitted: true } },
	});
	console.log('submitted for review');
}

const command = process.argv[2];
try {
	switch (command) {
		case 'status': await status(); break;
		case 'metadata': await metadata(); break;
		case 'screenshots': await screenshots(); break;
		case 'age-rating': await ageRating(); break;
		case 'categories': await categories(); break;
		case 'privacy-url': await privacyUrl(); break;
		case 'build': await attachBuild(); break;
		case 'review-detail': await reviewDetail(); break;
		case 'submit': await submit(); break;
		default:
			console.error('commands: status | metadata | screenshots | age-rating | build | submit');
			process.exit(2);
	}
} catch (error) {
	console.error(String(error.message ?? error));
	process.exit(1);
}
